#!/usr/bin/env python3
"""Opskeep-project-gate state machine. The only thing that may mark a gate approved.

  gate.py validate  [--state F]
  gate.py status    [--state F]
  gate.py apply     --response FILE|-  [--state F]     # dashboard response (approve / changes / alternative)
  gate.py approve-chat --quote "Approve Project Gate" [--state F]
  gate.py seal      [--state F]                        # after the prose docs are written -> gate.json
  gate.py verify    [--dir D]                          # drift check for downstream skills/agents
  gate.py reopen    --id PG-001 [--id PG-004] --reason "..." [--state F]

Default package dir: .opskeep/project-gate  (state lives at <dir>/state.json)
"""
import argparse
import datetime
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import gatelib as G  # noqa: E402

DIR_DEFAULT = ".opskeep/project-gate"
PROSE_DOCS = ["DESIGN.md", "screens.md", "components.md", "responsive.md", "accessibility.md"]
GENERATED = ["PROJECT.md", "assumptions.md", "decisions.yaml", "tokens.json", "intake.yaml"]


def now():
    return datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def die(msg, code=1):
    print(msg, file=sys.stderr)
    sys.exit(code)


def load_state(a):
    p = pathlib.Path(a.state or f"{a.dir}/state.json")
    if not p.exists():
        die(f"state not found: {p}")
    return p, json.loads(p.read_text(encoding="utf-8"))


def save_state(p, s):
    p.write_text(json.dumps(s, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def gate(s):
    return s.setdefault("gate", {"status": "not_approved", "history": []})


def log(s, event, detail=""):
    gate(s).setdefault("history", []).append({"at": now(), "event": event, "detail": detail})


# ---------------- generated package files ----------------
def write_generated(s, d):
    d.mkdir(parents=True, exist_ok=True)
    slug = s["project"]["slug"]
    sel = next(x for x in s["directions"] if x["id"] == s["selected_direction"])

    decisions = []
    for x in s["decisions"]:
        row = {k: x[k] for k in ("id", "area", "title", "value", "status") if k in x}
        if x.get("confirmed_via"):
            row["confirmed_via"] = x["confirmed_via"]
        if x.get("rationale"):
            row["rationale"] = x["rationale"]
        if x.get("depends_on"):
            row["depends_on"] = x["depends_on"]
        decisions.append(row)
    y = {"project": slug, "gate": gate(s)["status"], "direction": sel["id"] + " - " + sel["name"],
         "decisions": decisions}
    (d / "decisions.yaml").write_text("# Generated by Opskeep-project-gate. Change decisions via gate.py, not by hand.\n"
                                      + G.yaml_dump(y) + "\n", encoding="utf-8")

    tokens = {"meta": {"project": slug, "direction": sel["name"], "generated_by": "Opskeep-project-gate"}}
    tokens.update(sel["tokens"])
    (d / "tokens.json").write_text(json.dumps(tokens, indent=2) + "\n", encoding="utf-8")

    st = s["strategy"]
    intake = {
        "constraint": {"statement": st["constraint"]["statement"], "evidence": st["constraint"].get("evidence", "")},
        "forces": {k: (st.get("forces") or {}).get(k, "") for k in ("push", "pull", "anxiety", "habit")},
        "existing_assets": st["existing_assets"],
        "bet": {k: st["bet"][k] for k in ("belief", "wager", "expected_outcome", "leading_indicator")},
        "outcomes": st["outcomes"],
        "rejected_options": G.rejected_options(s),
    }
    (d / "intake.yaml").write_text(
        "# Generated by Opskeep-project-gate. The Opskeep/Elliot security gate copies this under project.intake in\n"
        "# security-baseline.yaml. Change it via gate.py (reopen), not by hand.\n" + G.yaml_dump({"intake": intake}) + "\n",
        encoding="utf-8")

    p = s["project"]
    md = [f"# {p['name']} — Project brief", "", p.get("one_liner", ""), ""]
    c, b = st["constraint"], st["bet"]
    md += ["## The problem", "", f"**Constraint:** {c['statement']}"]
    if c.get("evidence"):
        md += ["", f"**Evidence:** {c['evidence']}"]
    fr = st.get("forces") or {}
    if any(fr.values()):
        md += ["", "**Forces on the people served**", ""] + [f"- {k.title()}: {fr[k]}" for k in ("push", "pull", "anxiety", "habit") if fr.get(k)]
    md += ["", "**Already working or existing:** " + "; ".join(st["existing_assets"]), "",
           "## The bet", "",
           f"We believe {b['belief']}, so we are betting {b['wager']} that this produces {b['expected_outcome']}. "
           f"We will watch {b['leading_indicator']}.", "", "**Outcomes**", ""] + [f"- {o}" for o in st["outcomes"]]
    md += ["", "## Paths considered and rejected", ""] + [f"- **{r['option']}** — {r['reason']}" for r in G.rejected_options(s)] + [""]
    md += ["## Intent", ""] + [f"- **{r['label']}:** {r['value']}" for r in s.get("intent", [])]
    md += ["", "## Product character", ""] + [f"- {t['trait']}: {t['score']}%" for t in s.get("character", [])]
    md += ["", f"## Chosen direction: {sel['name']}", "", sel["tagline"], "", sel["fit"], ""]
    for area, title in (("users", "Users & jobs"), ("project", "Project")):
        rows = [x for x in s["decisions"] if x["area"] == area and x["status"] != "SUPERSEDED"]
        if rows:
            md += [f"## {title}", ""] + [f"- **{x['id']} {x['title']}** — {x['value']}" for x in rows] + [""]
    if s.get("risks"):
        md += ["## Risks", ""] + [f"- ({r.get('severity', 'med')}) {r['text']}" for r in s["risks"]] + [""]
    (d / "PROJECT.md").write_text("\n".join(md) + "\n", encoding="utf-8")

    by_gate = [x for x in s["decisions"] if x.get("confirmed_via") == "gate_approval"]
    am = [f"# {p['name']} — Assumptions", "",
          "Assumptions the builder saw but did not individually confirm. If one is wrong, reopen it:",
          "`gate.py reopen --id PG-xxx --reason \"...\"`", ""]
    am += [f"- **{a['id']}** {a['text']}" for a in s.get("assumptions", [])] or ["- (none recorded)"]
    am += ["", "## Decisions confirmed by gate approval (not individually reviewed)", ""]
    am += [f"- **{x['id']} {x['title']}** — {x['value']}" for x in by_gate] or ["- (none)"]
    (d / "assumptions.md").write_text("\n".join(am) + "\n", encoding="utf-8")


# ---------------- commands ----------------
def cmd_validate(a):
    _, s = load_state(a)
    errs, warns = G.validate(s)
    for e in errs:
        print("ERROR  ", e)
    for w in warns:
        print("warning", w)
    print("valid" if not errs else f"{len(errs)} error(s)")
    sys.exit(1 if errs else 0)


def cmd_status(a):
    _, s = load_state(a)
    c = G.counts(s)
    print(f"{s['project']['name']}: gate={gate(s)['status']} readiness={G.readiness(s)}%")
    print("  " + "  ".join(f"{k.lower()}={v}" for k, v in c.items()))
    b = G.approval_blockers(s)
    print("  approvable" if not b else "  blockers:\n    - " + "\n    - ".join(b))


def apply_changes(s, changes):
    by_id = {d["id"]: d for d in s["decisions"]}
    for ch in changes:
        d = by_id.get(ch.get("id"))
        if not d:
            die(f"response references unknown decision {ch.get('id')}")
        if ch.get("status") not in G.STATUSES:
            die(f"invalid status {ch.get('status')} for {d['id']}")
        d["status"] = ch["status"]
        if ch.get("value"):
            d["value"] = ch["value"]
        if ch.get("choice"):
            d["choice"] = ch["choice"]
        if ch["status"] == "CONFIRMED":
            d["confirmed_via"] = "explicit"
        else:
            d.pop("confirmed_via", None)


def finish_approval(s, method, quote=None):
    for d in s["decisions"]:
        if d["status"] in ("INFERRED", "PROPOSED"):
            d["status"] = "CONFIRMED"
            d["confirmed_via"] = "gate_approval"
    g = gate(s)
    g.update({"status": "approved", "approved_at": now(), "approval_method": method})
    if quote:
        g["approval_quote"] = quote
    g.pop("reopened", None)
    log(s, "approved", f"via {method}")


def cmd_apply(a):
    p, s = load_state(a)
    raw = sys.stdin.read() if a.response == "-" else pathlib.Path(a.response).read_text(encoding="utf-8")
    r = json.loads(raw)
    if r.get("schema") != G.RESPONSE_SCHEMA:
        die(f"response schema must be {G.RESPONSE_SCHEMA}")
    if r.get("project") != s["project"]["slug"]:
        die("response is for a different project")
    action = r.get("action")
    stale = r.get("base_hash") != G.state_hash(s)
    if stale and action == "approve_project_gate":
        die("STALE: the dashboard this approval came from is out of date (the state changed after it was rendered). "
            "Re-render the dashboard and ask for approval again.", 3)
    if stale:
        print("note: response was made against an older render; applying its changes anyway")

    apply_changes(s, r.get("changes", []))
    if r.get("selected_direction"):
        s["selected_direction"] = r["selected_direction"]
    g = gate(s)
    if r.get("notes"):
        g["notes"] = r["notes"]

    if action == "approve_project_gate":
        blockers = G.approval_blockers(s)
        if blockers:
            save_state(p, s)  # keep the user's edits, but do not approve
            die("NOT APPROVED. Blockers:\n  - " + "\n  - ".join(blockers), 2)
        finish_approval(s, "dashboard")
        write_generated(s, p.parent)
        save_state(p, s)
        print("APPROVED (design direction only; implementation_authorized stays false).")
        print(f"wrote {', '.join(GENERATED)} in {p.parent}")
        print("Next: author " + ", ".join(PROSE_DOCS) + " from the confirmed decisions, then run: gate.py seal")
    elif action in ("request_changes", "explore_alternative"):
        g["status"] = "changes_requested" if action == "request_changes" else "exploring_alternative"
        log(s, g["status"], r.get("notes", ""))
        save_state(p, s)
        print(f"gate status: {g['status']}. Revise decisions/directions, then re-render the dashboard.")
    else:
        die(f"unknown action {action!r}")


def cmd_approve_chat(a):
    if not a.quote.strip():
        die("--quote must contain the user's own words")
    p, s = load_state(a)
    blockers = G.approval_blockers(s)
    if blockers:
        die("NOT APPROVED. Blockers:\n  - " + "\n  - ".join(blockers), 2)
    finish_approval(s, "chat", a.quote.strip())
    write_generated(s, p.parent)
    save_state(p, s)
    print("APPROVED via chat quote. Next: author the prose docs, then gate.py seal")


def cmd_seal(a):
    p, s = load_state(a)
    g = gate(s)
    if g["status"] != "approved":
        die(f"cannot seal: gate status is {g['status']!r}, not 'approved'", 2)
    d = p.parent
    missing = []
    for name in GENERATED + PROSE_DOCS:
        f = d / name
        if not f.exists():
            missing.append(f"{name}: missing")
        elif name in PROSE_DOCS:
            t = f.read_text(encoding="utf-8")
            if len(t.strip()) < 300:
                missing.append(f"{name}: too short to be a real document")
            if "{{" in t or "TODO" in t:
                missing.append(f"{name}: contains placeholder text ({{{{ or TODO)")
    if missing:
        die("cannot seal:\n  - " + "\n  - ".join(missing), 2)
    sel = next(x for x in s["directions"] if x["id"] == s["selected_direction"])
    c = G.counts(s)
    via = [x.get("confirmed_via") for x in s["decisions"] if x["status"] == "CONFIRMED"]
    proof = {
        "skill": "Opskeep-project-gate",
        "version": G.VERSION,
        "project": s["project"]["name"],
        "status": "approved",
        "approved_at": g.get("approved_at"),
        "approval_method": g.get("approval_method"),
        "implementation_authorized": False,
        "next_gate": "opskeep-elliot-design",
        "direction": {"id": sel["id"], "name": sel["name"]},
        "decisions": {
            "confirmed": c["CONFIRMED"], "inferred": c["INFERRED"],
            "open": c["NEEDS_INPUT"] + c["PROPOSED"], "blocking": len(G.active_conflicts(s)) + c["REJECTED"],
            "confirmed_explicitly": sum(1 for v in via if v in ("interview", "explicit")),
            "confirmed_by_gate_approval": sum(1 for v in via if v == "gate_approval"),
        },
        "state_hash": G.state_hash(s),
        "files": {n: G.sha256_file(d / n) for n in GENERATED + PROSE_DOCS + ["state.json"]},
        "history": g.get("history", []),
    }
    (d / "gate.json").write_text(json.dumps(proof, indent=2) + "\n", encoding="utf-8")
    print(f"sealed {d / 'gate.json'} — Project Gate PASSED. Implementation is still NOT authorized; "
          "next gate: opskeep-elliot-design.")


def cmd_verify(a):
    d = pathlib.Path(a.dir)
    gj = d / "gate.json"
    if not gj.exists():
        die("NO GATE: gate.json missing. Project Gate has not passed.", 2)
    proof = json.loads(gj.read_text(encoding="utf-8"))
    if proof.get("status") != "approved":
        die(f"GATE {proof.get('status', '?').upper()}: not approved. Do not build.", 2)
    drift = []
    for name, h in proof.get("files", {}).items():
        f = d / name
        if not f.exists():
            drift.append(f"{name}: missing")
        elif G.sha256_file(f) != h:
            drift.append(f"{name}: changed since approval")
    if drift:
        die("DRIFT since approval (reopen the affected decisions instead of editing by hand):\n  - "
            + "\n  - ".join(drift), 1)
    print(f"OK: gate approved for '{proof['project']}', direction {proof['direction']['name']}, "
          f"implementation_authorized={str(proof['implementation_authorized']).lower()}, "
          f"next_gate={proof['next_gate']}")


def cmd_reopen(a):
    p, s = load_state(a)
    by_id = {d["id"]: d for d in s["decisions"]}
    for i in a.id:
        if i not in by_id:
            die(f"unknown decision {i}")
    affected, frontier = set(a.id), list(a.id)
    while frontier:  # transitive dependents
        cur = frontier.pop()
        for d in s["decisions"]:
            if cur in d.get("depends_on", []) and d["id"] not in affected:
                affected.add(d["id"])
                frontier.append(d["id"])
    for i in sorted(affected):
        d = by_id[i]
        if d["status"] == "SUPERSEDED":
            continue
        d["status"] = "NEEDS_INPUT"
        d.pop("confirmed_via", None)
        d["question"] = d.get("question") or f"Reconsider: {d['title']}"
        d["reopened_because"] = a.reason if i in a.id else f"depends on {', '.join(x for x in a.id)}"
    g = gate(s)
    g["status"] = "reopened"
    g["reopened"] = sorted(affected)
    log(s, "reopened", f"{', '.join(a.id)}: {a.reason}")
    save_state(p, s)
    gj = p.parent / "gate.json"
    if gj.exists():
        proof = json.loads(gj.read_text(encoding="utf-8"))
        proof.update({"status": "reopened", "implementation_authorized": False, "reopened": sorted(affected)})
        proof.setdefault("history", []).append({"at": now(), "event": "reopened", "detail": a.reason})
        gj.write_text(json.dumps(proof, indent=2) + "\n", encoding="utf-8")
    print(f"reopened {len(affected)} decision(s): {', '.join(sorted(affected))}")
    print(f"untouched: {len(s['decisions']) - len(affected)} decision(s). Re-render the dashboard and ask again.")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=DIR_DEFAULT)
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("validate", "status", "seal"):
        sp = sub.add_parser(name)
        sp.add_argument("--state")
    sp = sub.add_parser("apply")
    sp.add_argument("--response", required=True)
    sp.add_argument("--state")
    sp = sub.add_parser("approve-chat")
    sp.add_argument("--quote", required=True)
    sp.add_argument("--state")
    sub.add_parser("verify")
    sp = sub.add_parser("reopen")
    sp.add_argument("--id", action="append", required=True)
    sp.add_argument("--reason", required=True)
    sp.add_argument("--state")
    a = ap.parse_args()
    {"validate": cmd_validate, "status": cmd_status, "apply": cmd_apply, "approve-chat": cmd_approve_chat,
     "seal": cmd_seal, "verify": cmd_verify, "reopen": cmd_reopen}[a.cmd](a)


if __name__ == "__main__":
    main()
